# Extracts the production pieces needed by the config-reload checks.
# Real files (SelectionConfig, StartingOptionsConfig, StartingOptions,
# IndividualExclusions) are compiled directly by Reload.csproj.
# Usage: python generate.py [--mutant no-guard|no-reload|no-panel-reload]
import sys
